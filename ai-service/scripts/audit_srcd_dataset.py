"""Audit local CASA annotations and video mappings without preprocessing media."""
from __future__ import annotations

import csv
from collections import Counter
from pathlib import Path
import cv2
import pandas as pd


ROOT = Path(__file__).resolve().parents[1] / "data" / "casa"
OUTPUT = ROOT / "audit_report.md"
EXPECTED = {"media_file", "start", "end"}


def video_metadata(path: Path) -> dict:
    cap = cv2.VideoCapture(str(path))
    opened = cap.isOpened()
    fps = cap.get(cv2.CAP_PROP_FPS) if opened else 0.0
    frames = cap.get(cv2.CAP_PROP_FRAME_COUNT) if opened else 0.0
    width = cap.get(cv2.CAP_PROP_FRAME_WIDTH) if opened else 0.0
    height = cap.get(cv2.CAP_PROP_FRAME_HEIGHT) if opened else 0.0
    cap.release()
    duration = frames / fps if fps and fps > 0 else None
    return {"name": path.name, "bytes": path.stat().st_size, "opened": opened,
            "fps": fps or None, "frames": int(frames) if frames else None,
            "width": int(width) if width else None, "height": int(height) if height else None,
            "duration": duration}


def pct(n: int, d: int) -> str:
    return f"{100*n/d:.1f}%" if d else "n/a"


def main() -> None:
    lines = ["# CASA dataset audit for SRCD-GRU", "",
             "Generated by `scripts/audit_srcd_dataset.py`. Video metadata is probed from local files; CSVs are read only.",
             "", "## Summary", "",
             "The local media do not establish a complete, unambiguous annotation-to-video mapping. Exact stem matching is the only mapping applied; unmatched videos/annotations are not joined by similarity or inferred identity.",
             "Participant identity cannot be reliably recovered from the available mapping alone. No participant-independent training or test metrics should be reported until identities are resolved.", ""]
    total_videos = total_media = total_annotated = total_exclusions = 0
    for task in ("interview", "reading"):
        folder = ROOT / task
        csv_files = sorted(folder.glob("*.csv"))
        annotation_path = folder / "total_dataset.csv"
        raw_path = folder / "raw.csv"
        exclusion_path = folder / "exclusions.csv"
        if not annotation_path.is_file():
            continue
        annotations = pd.read_csv(annotation_path)
        raw = pd.read_csv(raw_path) if raw_path.is_file() else pd.DataFrame()
        exclusions = pd.read_csv(exclusion_path) if exclusion_path.is_file() else pd.DataFrame()
        video_paths = sorted(p for p in (folder / "videos").glob("*") if p.is_file())
        video_stems = {p.stem for p in video_paths}
        annotation_stems = set(annotations.media_file.dropna().astype(str).str.strip())
        matched = sorted(video_stems & annotation_stems)
        missing = sorted(annotation_stems - video_stems)
        orphan = sorted(video_stems - annotation_stems)
        total_videos += len(video_paths)
        total_media += annotations.media_file.nunique()
        total_annotated += len(annotations)
        total_exclusions += len(exclusions)
        lines += [f"## {task.title()}", "",
                  f"CSV files: {', '.join(p.name for p in csv_files) or 'none'}.",
                  f"`total_dataset.csv`: {len(annotations):,} rows, {annotations.media_file.nunique()} unique media IDs.",
                  f"`raw.csv`: {len(raw):,} rows; unaggregated label strings. `exclusions.csv`: {len(exclusions):,} intervals.",
                  f"Videos: {len(video_paths)}; exact stem matches: {len(matched)}; annotation media without local video: {len(missing)}; local videos without annotation media: {len(orphan)}.",
                  f"Exact matches: {', '.join(matched) if matched else 'none'}.",
                  f"Missing local videos: {', '.join(missing) if missing else 'none'}.",
                  f"Orphan local videos: {', '.join(orphan) if orphan else 'none'}.", "",
                  "Annotation columns: `" + "`, `".join(map(str, annotations.columns)) + "`.",
                  "Column meanings per CASA README: `media_file` is the media stem; `item` is the grouped interval ID; `start`/`end` are milliseconds; `annotator` identifies individual annotators or aggregation method; `SR, ISR, MUR, P, B, V, FG, HM, ME, T` are binary behavior indicators.",
                  f"Annotator counts: {annotations.annotator.value_counts().to_dict()}.",
                  f"Official split counts by media: {annotations.groupby('media_file').split.first().value_counts().to_dict()}."]
        for who in ("Gold", "bau"):
            rows = annotations[annotations.annotator.astype(str).str.casefold() == who.casefold()]
            if not len(rows):
                continue
            fg, hm = rows.FG.astype(int), rows.HM.astype(int)
            counts = {"FG positive": int(fg.sum()), "HM positive": int(hm.sum()),
                      "both positive": int(((fg == 1) & (hm == 1)).sum()),
                      "confirmed negative": int(((fg == 0) & (hm == 0)).sum())}
            lines += [f"", f"{who} aggregation ({len(rows)} intervals): {counts}; proportions FG={pct(counts['FG positive'],len(rows))}, HM={pct(counts['HM positive'],len(rows))}, both={pct(counts['both positive'],len(rows))}, negative={pct(counts['confirmed negative'],len(rows))}.",
                      f"{who} media IDs: {', '.join(sorted(rows.media_file.astype(str).unique()))}."]
        lines += ["", "### Exclusion and data-quality checks", ""]
        if len(exclusions):
            invalid = int(((pd.to_numeric(exclusions.start, errors="coerce") < 0) |
                           (pd.to_numeric(exclusions.end, errors="coerce") <= pd.to_numeric(exclusions.start, errors="coerce")) |
                           pd.to_numeric(exclusions.start, errors="coerce").isna() |
                           pd.to_numeric(exclusions.end, errors="coerce").isna()).sum())
            lines.append(f"Exclusions reference {exclusions.media_file.nunique()} media IDs; {invalid} invalid timestamp rows. Exclusions are unannotated regions according to CASA README and must be masked, not labelled NONE.")
        else:
            lines.append("No `exclusions.csv` present for this task.")
        invalid_ann = int(((pd.to_numeric(annotations.start, errors="coerce") < 0) |
                           (pd.to_numeric(annotations.end, errors="coerce") <= pd.to_numeric(annotations.start, errors="coerce")) |
                           pd.to_numeric(annotations.start, errors="coerce").isna() |
                           pd.to_numeric(annotations.end, errors="coerce").isna()).sum())
        duplicate_n = int(annotations.duplicated().sum())
        lines.append(f"Invalid annotation timestamps: {invalid_ann}; exact duplicate rows: {duplicate_n}.")
        lines += ["", "### Local video metadata", "",
                  "| File | Size (MiB) | Duration (s) | FPS | Resolution | Opened |",
                  "|---|---:|---:|---:|---:|---|"]
        metadata = [video_metadata(p) for p in video_paths]
        for m in metadata:
            duration = f"{m['duration']:.2f}" if m["duration"] is not None else "unknown"
            fps = f"{m['fps']:.3f}" if m["fps"] is not None else "unknown"
            res = f"{m['width']}×{m['height']}" if m["width"] and m["height"] else "unknown"
            lines.append(f"| {m['name']} | {m['bytes']/1048576:.2f} | {duration} | {fps} | {res} | {m['opened']} |")
        lines.append("")
    lines += ["## Mapping and participant conclusions", "",
              "Video-to-annotation matching used exact equality between the local video filename stem and the CSV `media_file` value, separately within each task directory. No fuzzy matching was attempted.",
              "The CASA README documents `media_file` as a media filename stem and says that media assets are separately downloaded. It does not establish that different media stems with shared prefixes are the same or different participants. Therefore the same-participant relationship across recordings/tasks remains unresolved, and split-leakage checks by participant cannot be certified.",
              "CASA `total_dataset.csv` includes `Gold` and BAU/MAS/SAD aggregation rows; these are not independent annotators. In these files Gold rows occur only in the official test split. The local exact-matched interview set therefore does not provide Gold-labelled development and test partitions together. If aggregation rows are used later, select one documented aggregation consistently and keep Gold separate for evaluation.",
              "FG and HM can co-occur: the source table contains rows with both indicators equal to 1. Preserve independent binary targets. CASA FG is broad (jaw jerking, tongue protrusion, lip pressing, jaw-muscle tension, eye movements); it does not isolate the narrower facial grimacing/tension interpretation without additional annotation. CASA HM is back/forward/turning-away movement. This scope question remains unresolved for Swara's target.",
              "### Current environment and training readiness", "",
              "The repository's `one.venv` has OpenCV 4.11.0 and MediaPipe 0.10.21, and `ai-service/models/face_landmarker.task` is present. PyTorch is not installed in that environment. MediaPipe provides one face and can emit blendshapes and transformation matrices, but the current analyzer only persists a small set of scalar movement channels rather than all 52 blendshapes.",
              "Training is intentionally blocked: local media mapping is incomplete, participant grouping is unverified, Gold is confined to the official test split, and the feature cache for eligible mapped media does not exist. No model was trained and no evaluation metrics are claimed.",
              "## CASA documentation consulted", "",
              "- CASA repository README: https://github.com/mbzuai-nlp/CASA (dataset layout, column meanings, millisecond units, exclusion semantics, official split fields, and the original preprocessing estimate of >130 GB RAM).",
              "- CASA annotation guideline: https://github.com/mbzuai-nlp/CASA/blob/main/docs/guidlines.md (behavior definitions and co-occurrence rule).",
              "", f"Audit totals: {total_videos} local videos, {total_media} task-specific annotated media IDs, {total_annotated:,} aggregate annotation rows, {total_exclusions:,} exclusion rows.", ""]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
